// Drives the REAL TriggerEngine with the REAL output of the generation
// pipeline's assembleTour() (apps/api/src/stages/narration/assemble.ts) —
// the only test in Plan 2a that proves the pipeline's output is actually
// playable, rather than merely well-formed.
//
// apps/web cannot import apps/api directly (that would be a cross-app
// workspace dependency neither app currently declares, and casually adding
// one is worse than the alternative — see task-8-report.md for the
// reasoning). Instead, both apps depend on @ai-guide/shared already, so the
// assembled Tour lives there as a static, checked-in fixture:
// packages/shared/src/fixtures/bratislava-tour.json.
//
// That fixture is NOT hand-typed. It is generated by
// apps/api/scripts/generate-tour-fixture.ts from the same recorded routing
// cassette and hand-authored synthetic curation/narration cassettes that
// apps/api's own tests use, and apps/api/src/stages/narration/assemble.test.ts
// asserts assembleTour(...) reproduces it exactly — so this file is always
// testing a real, current, reproducible pipeline output, not a fixture that
// has quietly drifted from what the code actually does.
import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import { readFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TourSchema, haversineM, type Tour } from '@ai-guide/shared';

/** Normal walking pace, and the same value the simulator is driven at. */
const WALKING_SPEED_MPS = 1.4;
import { TriggerEngine } from './engine';
import { SimulatedLocation } from '../location/simulated';

const here = dirname(fileURLToPath(import.meta.url));
const fixturePath = join(
  here,
  '..',
  '..',
  '..',
  '..',
  '..',
  'packages',
  'shared',
  'src',
  'fixtures',
  'bratislava-tour.json',
);

async function loadFixture(): Promise<{ generated: boolean; comment: string; tour: unknown }> {
  const raw = await readFile(fixturePath, 'utf8');
  const parsed = JSON.parse(raw) as { _generated: boolean; _comment: string; tour: unknown };
  return { generated: parsed._generated, comment: parsed._comment, tour: parsed.tour };
}

describe('assembled Bratislava tour fixture', () => {
  it('is marked as generated (not hand-typed) and parses against TourSchema', async () => {
    const { generated, tour } = await loadFixture();
    expect(generated).toBe(true);

    const result = TourSchema.safeParse(tour);
    expect(result.success).toBe(true);
  });

  describe('driving the real TriggerEngine', () => {
    beforeEach(() => vi.useFakeTimers());
    afterEach(() => vi.useRealTimers());

    /** Walks the fixture's recorded route with a real TriggerEngine and
     * returns every segment that fired, in the order it fired. */
    async function walkTheRoute(): Promise<{ tour: Tour; fired: { id: string; order: number }[] }> {
      const { tour: rawTour } = await loadFixture();
      const tour = TourSchema.parse(rawTour) as Tour;

      const engine = new TriggerEngine(tour);
      // A normal walking pace, one GPS fix per second — the same cadence the
      // real app's LocationProvider uses.
      const sim = new SimulatedLocation(tour.routeGeoJson, {
        speedMps: WALKING_SPEED_MPS,
        intervalMs: 1000,
        accuracyM: 10,
      });

      const fired: { id: string; order: number }[] = [];
      sim.start((fix) => {
        for (const event of engine.onFix(fix)) {
          if (event.type === 'fire') fired.push({ id: event.segment.id, order: event.segment.order });
        }
      });

      // Derived from the route, never hard-coded. A fixed 40 minutes was
      // sized for an earlier 2km fixture; when real curation produced a
      // 5.2km route the walker simply ran out of clock two-thirds of the way
      // along, and ten segments "failed to fire" for no reason but that.
      // A stale constant that silently truncates the walk is indistinguishable
      // from an engine bug in the failure output.
      const coords = tour.routeGeoJson.coordinates;
      let routeM = 0;
      for (let i = 1; i < coords.length; i++) {
        routeM += haversineM(
          { lat: coords[i - 1][1], lng: coords[i - 1][0] },
          { lat: coords[i][1], lng: coords[i][0] },
        );
      }
      const walkMs = (routeM / WALKING_SPEED_MPS) * 1000;
      vi.advanceTimersByTime(Math.ceil(walkMs * 1.5));
      sim.stop();

      return { tour, fired };
    }

    it('fires every triggered segment exactly once, with none skipped or repeated', async () => {
      const { tour, fired } = await walkTheRoute();
      const triggeredSegments = tour.segments.filter((s) => s.trigger !== null);

      expect(fired).toHaveLength(triggeredSegments.length);
      expect(new Set(fired.map((f) => f.id)).size).toBe(fired.length);
      expect(new Set(fired.map((f) => f.id))).toEqual(new Set(triggeredSegments.map((s) => s.id)));
    });

    // KNOWN, DIAGNOSED FAILURE — kept strict and unweakened rather than
    // deleted or loosened, per an explicit instruction not to paper over
    // exactly this kind of finding.
    //
    // Root cause, traced end to end:
    //   1. assembleTour gives each `walk` segment the SAME triggerRadiusM as
    //      the stop it departs from (per task-8-brief.md step 4). On the
    //      real recorded Bratislava route this makes EVERY walk cue's zone
    //      overlap its departing stop's zone — e.g. stop order 9 and its
    //      walk cue (order 10) are 34.0m apart with radii of 43.1m each
    //      (radii sum 86.3m); stop order 13 and its walk cue (order 14) are
    //      68.9m apart with radii of 60.0m each (radii sum 120.0m). All 7
    //      of the tour's stop/walk-cue pairs overlap this way — confirmed
    //      numerically, not merely suspected.
    //   2. TriggerEngine sorted ready candidates by distance ALONE, so it did
    //      not prefer whichever came first in tour order. That was fine for
    //      two co-located stops, where order is arbitrary; a real route puts
    //      THREE candidates (a stop, its walk cue, and the next stop) in
    //      range at once when zones overlap this widely, and there order is
    //      not arbitrary at all.
    //   3. The recorded route's final leg (Hviezdoslavovo námestie ->
    //      Hlavné námestie) additionally passes within ~0.1m of its own
    //      earlier self at a different arc-length position — confirmed by
    //      projecting both this leg's true 25%-along cue point and the
    //      superseded cumulative-leg-distance-derived one back onto the
    //      geometry (see task-8-report.md). That self-proximity is a
    //      property of Mapbox's real walking directions for this street
    //      layout, not of how the cue point's fraction is computed.
    //
    // Net effect before the fix: orders 9/10 swapped and 13/14/15 fired as
    // 15/14/13 — every segment fired exactly once, but not in tour order.
    //
    // RESOLVED, after four attempts, and the fourth is the only one that
    // addressed the actual cause.
    //
    // The first three treated it as a geometry problem: break ties on tour
    // order rather than distance; make a walk cue wait for the stop it
    // departs from; project stop positions monotonically so a route returning
    // past an earlier stop cannot place that stop's cue a third of the way
    // through the tour. Each was a genuine improvement. None closed it,
    // because each still assumed a cue is a PLACE.
    //
    // On this real 5.2km route — which crosses itself twice, passing within a
    // metre of its own earlier path — a cue's 25%-along-the-leg point can sit
    // nearer to a later part of the walk than to the leg it belongs to. No
    // projection fixes that, because proximity was standing in for progress
    // and on a self-intersecting route it is not one.
    //
    // A walk cue is an EVENT, not a place: it belongs to the moment you leave
    // a stop. The engine can observe that directly — the walker was inside the
    // stop's radius, and now is not — and once it does, the cue radius, the
    // projection and the whole failure class stop existing.
    //
    // Kept strict throughout rather than loosened to something that would
    // pass. An ordering test that tolerates disorder proves nothing, and this
    // one found three separate real defects before it found this one.
    it('fires segments in ascending tour order', async () => {
      const { tour, fired } = await walkTheRoute();
      const triggeredSegments = tour.segments.filter((s) => s.trigger !== null);

      expect(fired.map((f) => f.order)).toEqual(triggeredSegments.map((s) => s.order));
    });
  });
});
